  let lang = localStorage.getItem('wm-lang');
  if (!lang) {
    lang = (navigator.language || 'zh').toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }

  function t(key) {
    const table = dict[lang] || dict.zh;
    return table[key] !== undefined ? table[key] : dict.zh[key];
  }

  function applyI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const text = t(el.dataset.i18n);
      if (typeof text === 'string') el.textContent = text;
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const text = t(el.dataset.i18nHtml);
      if (typeof text === 'string') el.innerHTML = text;
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const text = t(el.dataset.i18nTitle);
      if (typeof text === 'string') el.title = text;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const text = t(el.dataset.i18nPlaceholder);
      if (typeof text === 'string') el.placeholder = text;
    });
    // 图标型按钮（只有 emoji/缩写）必须靠 aria-label 才能被读屏器念出来
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const text = t(el.dataset.i18nAria);
      if (typeof text === 'string') el.setAttribute('aria-label', text);
    });
    document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
    document.title = lang === 'en' ? 'Watermark Cleaner' : '水印清理';
  }

  function setLang(next) {
    lang = next;
    localStorage.setItem('wm-lang', next);
    applyI18n();
  }

  window.i18n = { t, applyI18n, setLang, get lang() { return lang; } };

